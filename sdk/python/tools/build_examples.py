#: A description is the heading and at most this much of the paragraph under the SQL.
DESCRIPTION_LIMIT = 420

_LINK = re.compile(r"\(sql/(?P<file>[0-9]{2}-continuous-[a-z0-9-]+\.sql)\)")
_HEADING = re.compile(r"^(#{1,6})\s+(.+?)\s*$")
_STEP = re.compile(r"^Step\s+\w+\s+[—-]\s+", re.IGNORECASE)
_WORD = re.compile(r"[A-Za-z_][A-Za-z0-9_]*")

